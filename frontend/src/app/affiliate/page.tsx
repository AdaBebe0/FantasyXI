"use client";

import React, { useEffect, useState } from "react";
import { useToast } from "@/context/ToastContext";
import { IconCopy, IconCheck } from "@/components/ui/Icons";

interface AffiliateData {
  referralCode: string;
  referralLink: string;
  totalReferrals: number;
  activeReferrals: number;
  totalEarnedUsdc: number;
  referrees: Array<{
    id: string;
    username: string;
    joinedAt: string;
  }>;
}

export default function AffiliateDashboardPage() {
  const { toast } = useToast();
  const [data, setData] = useState<AffiliateData | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    const fetchAffiliateData = async () => {
      try {
        setLoading(true);
        const token = localStorage.getItem("token");
        const apiUrl = process.env.NEXT_PUBLIC_API_URL || "http://localhost:5000";

        const res = await fetch(`${apiUrl}/api/v1/financial/affiliate-dashboard`, {
          headers: {
            Authorization: `Bearer ${token}`,
          },
        });

        if (!res.ok) throw new Error("Failed to fetch affiliate dashboard data");
        const json = await res.json();
        setData(json.data);
      } catch (err: unknown) {
        const msg = err instanceof Error ? err.message : "An error occurred";
        setError(msg);
        toast.error(msg);
      } finally {
        setLoading(false);
      }
    };

    fetchAffiliateData();
  }, [toast]);

  const handleCopy = () => {
    if (data?.referralLink) {
      navigator.clipboard.writeText(data.referralLink);
      setCopied(true);
      toast.success("Affiliate referral link copied to clipboard!");
      setTimeout(() => setCopied(false), 2000);
    }
  };

  return (
    <div className="space-y-6 pb-12">
      <div className="max-w-6xl mx-auto space-y-6">
        <header className="bg-white border border-slate-200/80 p-6 sm:p-8 rounded-3xl shadow-sm">
          <h1 className="text-2xl sm:text-3xl font-black text-slate-900 tracking-tight">
            Affiliate &amp; Referral Rewards
          </h1>
          <p className="text-xs sm:text-sm text-slate-500 mt-1 max-w-2xl leading-relaxed">
            Invite friends to paid leagues and automatically earn 20% of the platform fees generated by your referrals with on-chain settlement.
          </p>
        </header>

        {loading && (
          <div className="flex justify-center items-center py-20 text-slate-500 text-xs font-semibold">
            <div className="animate-spin rounded-full h-8 w-8 border-2 border-[#37003c] border-t-transparent mr-3"></div>
            Loading affiliate program details...
          </div>
        )}

        {error && (
          <div className="bg-rose-50 border border-rose-200 text-rose-700 p-4 rounded-xl text-xs font-semibold">
            Error loading affiliate data: {error}
          </div>
        )}

        {!loading && !error && data && (
          <div className="space-y-6">
            {/* Referral Link Share Box */}
            <section className="bg-white p-6 rounded-3xl border border-slate-200/80 shadow-sm space-y-4">
              <h2 className="text-sm font-bold uppercase tracking-wider text-slate-900">Your Unique Referral Link</h2>
              <div className="flex flex-col sm:flex-row gap-3">
                <input
                  type="text"
                  readOnly
                  value={data.referralLink}
                  className="flex-1 bg-slate-50 border border-slate-200 text-slate-800 font-mono text-xs px-4 py-2.5 rounded-xl focus:outline-none focus:border-[#37003c]"
                />
                <button
                  onClick={handleCopy}
                  className="bg-[#37003c] hover:bg-[#26002b] text-white font-bold px-6 py-2.5 rounded-xl transition flex items-center justify-center gap-2 text-xs shadow-xs"
                >
                  {copied ? (
                    <>
                      <IconCheck size={16} className="text-[#00ff87]" />
                      <span>Copied!</span>
                    </>
                  ) : (
                    <>
                      <IconCopy size={16} />
                      <span>Copy Link</span>
                    </>
                  )}
                </button>
              </div>
              <p className="text-xs text-slate-400">
                Share this link with your friends. Referral Code: <span className="font-mono font-bold text-slate-700">{data.referralCode}</span>
              </p>
            </section>

            {/* Metrics Overview Cards */}
            <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
              <div className="bg-white p-6 rounded-3xl border border-slate-200/80 shadow-sm">
                <span className="text-xs font-bold uppercase tracking-wider text-slate-400">Total Referrals</span>
                <div className="text-3xl font-black text-slate-900 mt-2 font-mono">{data.totalReferrals}</div>
              </div>
              <div className="bg-white p-6 rounded-3xl border border-slate-200/80 shadow-sm">
                <span className="text-xs font-bold uppercase tracking-wider text-slate-400">Active Paid Participants</span>
                <div className="text-3xl font-black text-[#37003c] mt-2 font-mono">{data.activeReferrals}</div>
              </div>
              <div className="bg-white p-6 rounded-3xl border border-slate-200/80 shadow-sm">
                <span className="text-xs font-bold uppercase tracking-wider text-slate-400">Total Earned Rewards</span>
                <div className="text-3xl font-black text-emerald-700 mt-2 font-mono">${data.totalEarnedUsdc.toFixed(2)} USDC</div>
              </div>
            </div>

            {/* Referred Users Table */}
            <section className="bg-white p-6 rounded-3xl border border-slate-200/80 shadow-sm space-y-4">
              <h2 className="text-sm font-bold uppercase tracking-wider text-slate-900">Referred Users</h2>
              {data.referrees.length === 0 ? (
                <p className="text-slate-400 text-xs py-4">No user referrals recorded yet. Copy and share your link above to get started!</p>
              ) : (
                <div className="overflow-x-auto rounded-xl border border-slate-200">
                  <table className="w-full text-left text-xs text-slate-700">
                    <thead className="text-[10px] uppercase bg-slate-50 text-slate-500 font-bold tracking-wider border-b border-slate-200">
                      <tr>
                        <th className="py-3 px-4">User</th>
                        <th className="py-3 px-4 text-right">Joined Date</th>
                      </tr>
                    </thead>
                    <tbody className="divide-y divide-slate-100">
                      {data.referrees.map((ref) => (
                        <tr key={ref.id} className="hover:bg-slate-50">
                          <td className="py-2.5 px-4 font-bold text-slate-900">{ref.username}</td>
                          <td className="py-2.5 px-4 text-right text-slate-500 font-mono">
                            {new Date(ref.joinedAt).toLocaleDateString()}
                          </td>
                        </tr>
                      ))}
                    </tbody>
                  </table>
                </div>
              )}
            </section>
          </div>
        )}
      </div>
    </div>
  );
}
